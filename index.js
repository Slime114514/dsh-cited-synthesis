const RULES = `## 检索交付规范

联网检索（web_search / web_fetch）后的交付，默认遵守：

1. 每条实质结论后跟一个链接，链接必须直接支持这句话本身，不接受"相关阅读"；数字若来自某篇综述转引的原始研究，写明转引自哪里。
2. 先分清断言类型，措辞不能混：可观测事实直接陈述；制度性事实（票价、开放时间）注明依据文件与日期；权威建议必须写成"某机构某年建议……"并标明适用人群，不能写成本来如此；有争议的判断按条件并列；你自己合成的建议必须标 [推断] 或明说"我的建议"，不能混进引用。
3. 结论写成"条件—结论"结构；来源没交代条件时写"条件未说明"，不要替它假设。
4. 主动找反例。存在相反结论时按条件并列，不要压成一句"存在争议"。
5. 标注证据类型：官方公告 / 同行评审 / 预印本 / 厂商自述 / 媒体或自媒体。
6. 凡超出单一来源的表述都标 [推断]：跨来源拼接、因果归因、跨研究排序、一句话总括、把关联转成处方。总括若只是压缩下文已标注的结论，可省；引入下文没有的判断则必须标。标了要写依据与推理步骤。
7. 专业分级代码（证据等级 2a、GRADE 高/低、Class I）要么当场一句话解释，要么换成读者能懂的话，不要直接甩出来。
8. 结尾列"未核实项"与"检索范围"。
9. 篇幅与"决策代价 × 真分歧"成正比：事实性问题一句话加一个链接；建议性问题必须带归属，不能靠缩短篇幅省掉。超长时先删重复与连接句，风险信息（来源冲突、概率、检修、未核实项）不删。

需要完整流程时加载 skill：${SKILL_NAME}。`

const SKILL = `# 检索交付规范（Cited Synthesis Delivery）

## 什么时候用

需要联网检索并给出结论的任务：旅行攻略、消费选购、事实核查、政策查询、学术调研。

不适用：纯代码任务、纯计算，以及用户明确要求"只要一句话"的场合。

## 一、先定检索范围

动笔前定三件事，并写进最终交付：

- 时间敏感度：价格、政策、开放时间、库存这类信息会变，要写明"截至什么时间"。
- 需要的来源类型：官方 / 专业媒体 / 用户实测 / 厂商。
- 什么算查够了：找到一个能覆盖反面证据的来源，或者连续几个来源都在说同一件事。

## 二、分清四种断言

同样一句话，属于哪一类决定了怎么写。写错类别，比写错数字更糟。

| 类型 | 例子 | 怎么核实 | 怎么写 |
|---|---|---|---|
| 可观测事实 | 月球绕地球运行；水在标准大气压下 100℃ 沸腾 | 观测、测量，与立场无关 | 直接陈述 |
| 制度性事实 | 某景区 11 月 16 日起执行淡季票价 | 查规则文本本身 | 陈述 + 依据文件 + 日期 |
| 权威建议 / 共识 | 成年人每日睡 7–8 小时；每周 150 分钟中等强度运动 | 查发布机构与年份 | "某机构某年建议……" + 适用人群 + 时点 |
| 争议判断 | 跑步是否伤膝；某地是否值得去 | 看证据是否分歧 | 按条件并列 |
| 自身建议 | "没有旧伤就不必回避休闲跑" | 没有外部来源，是前四类推出来的 | 标 [推断]，写出依据链，或明说"我的建议" |

三条硬规矩：

1. **建议不能写成事实。**"成年人需要 7–8 小时"是错的写法；"全国爱卫办 2025 年 3 月建议成年人每日 7–8 小时"才对。差别不在礼貌，在责任归属：前一句把机构的判断变成了世界的属性。
2. **建议要带时点和适用人群。**同一机构隔几年可能改口，不同国家口径也不一样。不写时点，读者无法判断是否过期。
3. **制度性事实要引到规则文本**，不是引到转述它的新闻。票价、开放时间、限速、申报期限都属于这一类。
4. **你自己的建议也是断言，同样要署名。**署名可以是机构，也可以是"我"。最糟的是不署名：读者分不清这句话是 WHO 说的，还是模型刚刚拼出来的。

归不了类的，不要硬归，写进"未核实项"。

## 三、建证据台账

每读一个页面记一行：

| 来源 | 它说了什么 | 成立条件 | 来源类型 | 发布时间 | 我核到什么程度 |
|---|---|---|---|---|---|

"核到什么程度"只有三档，不能混用：

- **已读正文**：打开页面并读到支持这句话的段落。只有这一档能支撑实质结论。
- **仅见摘要**：看到的是搜索结果的标题或摘要。只能当线索，不能当论据。
- **未打开**：从别处转述，自己没访问过。只能进未核实清单。

**转引要标转引。**数字如果是 A 综述引用 B 的原始研究得来的，写成"A 综述引用 B（年份）的数据"，不要写成 A 自己算的。读者顺着 A 找不到那个数，信任就断在这里。

## 四、把结论写成条件句

不要写"X 更好"，写"在 A 条件下 X 更好，在 B 条件下不成立"。

条件维度按领域换：

- 旅行：季节 / 人群 / 体力 / 预算 / 交通方式 / 时段
- 消费：使用强度 / 身体条件 / 预算 / 维护成本 / 使用年限
- 学术：样本 / 方法 / 指标 / 时间窗 / 地域
- 政策：适用对象 / 生效时间 / 地区 / 前置资格

来源没交代条件的，写"条件未说明"，不要替它补。

数字必须带不确定性。看到"OR 0.86"，就要看它的置信区间是否跨过 1；看到"平均 3.5%"，就要问这是哪个人群的合并值。点估计单独出现时，不要把方向说成结论。

## 五、处理分歧

先判断是不是真分歧，三步：

1. 两边在回答同一个问题吗？不是的话，不是分歧，是不相干。
2. 测量口径一样吗？不一样的话，两个数字不能比大小。
3. 剩下的才是真分歧，按条件并列。

真分歧的写法：

> 在【条件 A】下，来源 1 得到【结论 1】；在【条件 B】下，来源 2 得到【结论 2】。差异可能来自【样本 / 方法 / 时间 / 口径】。

不要为了显得全面而硬造对立面。证据一边倒时，如实写一边倒，并把"为什么看起来有争议"解释清楚。

## 六、标注推断

以下五类都算推断，必须标 [推断]，哪怕只有一句话：

1. **跨来源拼接**：把 A 的结论和 B 的结论合成一个新结论。
2. **因果归因**：说"是因为""导致了""主要来源是"。观察性研究只能给关联，把关联说成因果，中间那一步是推断。
3. **跨研究排序**："最稳定""最主要""最一致"——除非有一篇 Meta 直接做了这个排序。
4. **一句话总括**：开头的"结论先行"里，那句浓缩了多条证据的判断。若它只是把下文已标注的结论压缩一遍，可以不标；一旦引入下文没有的判断（比如从"不增加风险"滑到"能预防关节炎"），必须标。
5. **把关联转成处方**：从"HRR 1.64"推出"单次加量别超过 10%"，这一步是推断，不是那篇论文说的。

标的时候写三样：依据哪几条来源、怎么拼的、哪一步是自己的判断。

不标的后果只有一个：读者分不清这句是 WHO 说的，还是模型刚编的。

推断不是事实，不能混进引用段落，也不能在后续段落里当成前提复用。

## 七、交付格式

1. 结论（按条件分组，每组带链接，并标明断言类型）
2. 反例或分歧（如果有）
3. [推断]（如果有）
4. 未核实项
5. 检索范围与时间
6. 建议（如有，标 [推断] 并署名）

篇幅跟"决策代价 × 真分歧"成正比。买错机票和买错牙刷不该是一个篇幅。

## 八、交付前自检

交付前过一遍，只查冗余，不查表达。四条能机械执行的：

1. **重复合并**：同一个数字或事实出现两次以上，合并到一处。
2. **连接句删除**："需要注意的是""总的来说""另外值得一提的是"，删掉后语义不变的，一律删。
3. **长链接降级**：同一来源被引用三次以上，首次给完整链接，后文用"同上"或短标。
4. **抽样回滚**：删完随机抽三条结论，检查链接和条件还在不在；少一个就回滚这一处。

字数软上限：事实/操作类（攻略、价格、流程）≤1500 字，争议/判断类 ≤2500 字。超了按这个顺序压：重复 → 连接句 → 长链接 → 表格合并。**不删证据。**

最容易删错的是"条件未说明""未核实""样本小"这类短句：它们读起来最像废话，实际是全篇最值钱的部分。第 4 条就是用来兜住这一刀的。

**不可删清单。**以下四类即使显得啰嗦，压缩时一律保留：

1. 来源之间的不一致：谁和谁打架、差在哪。
2. 概率、不确定性、置信区间。
3. 时效性风险：检修、季节性调整、政策变动。
4. 未核实项。

**压缩的另一种事故。**把两个来源压进同一句话而不标来源，会产出"先写售票截止 16:00、紧接着又说官网写 16:30"这种自相矛盾的句子。来源不同就分开写；宁可多一句，不要多一个矛盾。

## 九、反模式

- 把"有链接"当成"有证据"：链接存在，不代表它支持这句话。
- 把建议写成事实："成年人需要睡 7–8 小时""每天必须喝八杯水"。
- 用"科学表明""研究表明""业内认为"代替具体机构与年份。
- 甩出分级代码不解释："证据等级 2a""GRADE 高"，读者不知道那是什么，等于没说。
- 把不同口径的数字放进一张表排名。
- 用"综合来看，各有优劣"抹掉真实分歧。
- 每条都强行加反例，制造虚假平衡。
- 引用自己没打开过的页面。
- 用记忆代替检索，尤其是在价格、政策、开放时间上。
- 把自己的综合判断写成陈述句：既没出处，也没标 [推断]，读者会当成事实。
- 自检时把"未核实""条件未说明"当废话删掉——那是全文最值钱的部分。
- 建议段落里出现"应该""不必""建议"却没有主语：是 WHO 建议的，还是你建议的？
- 用"导致""因为""主要原因"把两个来源连起来，却不标 [推断]。
- 用"最""普遍""一致"做跨研究概括，背后没有一篇 Meta 支撑。
- 把综述转引的原始研究数据，写成综述自己算出来的结果。
`

export function apply(ctx) {
  ctx.systemPrompt.section({
    name: SECTION_NAME,
    order: 40,
    text: RULES,
  })

  ctx.skills.register({
    name: SKILL_NAME,
    description:
      'Turn a web-search result into a cited, condition-indexed answer: separate facts from recommendations, carry a supporting link on every claim, list opposing findings with their conditions, and mark cross-source inferences. 检索交付规范：分清事实与建议、结论挂链接、写清成立条件、并列相反结论。',
    whenToUse:
      'Any task that searches the web and then reports conclusions: travel planning, product comparison, fact checking, policy or price lookup. 需要联网检索并给出结论时使用。',
    source: 'custom',
    content: SKILL,
    invocation: {
      modelInvocable: true,
      userInvocable: true,
    },
  })
}
